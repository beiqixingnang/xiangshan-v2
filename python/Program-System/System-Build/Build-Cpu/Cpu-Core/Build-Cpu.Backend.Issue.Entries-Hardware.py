def build_verilog(configuration=None, injected_dependencies=None) -> str:
    """Emit deterministic V2 issue-entries-family Verilog. / 输出确定性的 V2 issue 条目族 Verilog。"""

    del injected_dependencies
    from amaranth.back import verilog

    if configuration and configuration.get("module"):
        name = configuration["module"]
        top_name = configuration.get("top_name", name)
        if name not in COVERED_PORTS:
            raise KeyError("uncovered module: " + name)
        top = V2IssueEntryModule(name, COVERED_PORTS[name])
        return verilog.convert(top, name=top_name, ports=top.all_ports)
    top = UHSCBackendIssueEntriesFamily(COVERED_PORTS)
    return verilog.convert(top, name="UHSCBackendIssueEntriesFamily", ports=[])


