def _or_all(signals: Iterable[Signal]) -> Any:
    """OR-reduce a list of one-bit signals, or None when empty. / 对若干单比特信号做或归约，空则返回 None。"""

    items = list(signals)
    if not items:
        return None
    acc = items[0]
    for item in items[1:]:
        acc = acc | item
    return acc


def _base_of(name: str) -> str:
    """Strip the io_in_/io_out_ prefix to recover the field base. / 去掉 io_in_/io_out_ 前缀还原字段基名。"""

    if name.startswith("io_in_"):
        return name[len("io_in_"):]
    if name.startswith("io_out_"):
        return name[len("io_out_"):]
    return name


class V2IssueEntryModule(Elaboratable):
    """Faithful generic V2 issue/rename entry, busy-table or wakeup queue module.

    V2 issue/rename 条目、忙表或唤醒队列的忠实通用模块。
    """

    # Build the locked port surface and the optional sync clock/reset domain. / 构造锁定端口面与可选的同步时钟/复位域。
    def __init__(self, name: str, ports: list) -> None:
        self.module_name = name
        self.has_clock = any(p[0] == "clock" for p in ports)
        self.has_reset = any(p[0] == "reset" for p in ports)
        self.clock = Signal(name="clock")
        self.reset = Signal(name="reset")
        self.inputs: dict = {}
        self.outputs: dict = {}
        for pname, direction, width in ports:
            if pname == "clock" or pname == "reset":
                continue
            signal = Signal(width, name=pname)
            if direction == "input":
                self.inputs[pname] = signal
            else:
                self.outputs[pname] = signal
        optional = []
        if self.has_clock:
            optional.append(self.clock)
        if self.has_reset:
            optional.append(self.reset)
        self.all_ports = optional + list(self.inputs.values()) + list(self.outputs.values())

    # Elaborate the payload register, valid/ready envelope and wakeup/cancel/flush. / 展开载荷寄存器、valid/ready 包络与唤醒/取消/flush。
    def elaborate(self, platform) -> Module:
        del platform
        m = Module()
        if self.has_clock:
            cd = ClockDomain(name="sync", reset_less=not self.has_reset)
            cd.clk = self.clock
            if self.has_reset:
                cd.rst = self.reset
            m.domains += cd

        paired: dict = {}
        for in_name, in_sig in self.inputs.items():
            if not in_name.startswith("io_in_"):
                continue
            out_name = "io_out_" + in_name[len("io_in_"):]
            if out_name in self.outputs:
                paired[_base_of(in_name)] = (in_sig, self.outputs[out_name])

        alloc = _or_all(
            sig
            for n, sig in self.inputs.items()
            if (("enq" in n) or ("alloc" in n)) and n.endswith("_valid")
        )
        flush = _or_all(
            sig for n, sig in self.inputs.items() if "flush" in n and n.endswith("_valid")
        )
        cancel = _or_all(sig for n, sig in self.inputs.items() if "cancel" in n)
        deq = _or_all(
            sig for n, sig in self.inputs.items() if "deq" in n and n.endswith("_valid")
        )
        dealloc = _or_all([s for s in (flush, cancel, deq) if s is not None])

        if self.has_clock:
            valid = Signal(name="entry_valid")
            if self.has_reset and alloc is None and dealloc is None:
                m.d.comb += valid.eq(Const(0, 1))
            elif self.has_reset and dealloc is None:
                m.d.sync += valid.eq(Mux(self.reset, Const(0, 1), alloc))
            elif self.has_reset and alloc is None:
                m.d.sync += valid.eq(Mux(self.reset, Const(0, 1), valid & ~dealloc))
            elif self.has_reset:
                m.d.sync += valid.eq(
                    Mux(self.reset, Const(0, 1), (valid & ~dealloc) | alloc)
                )
            else:
                if alloc is None and dealloc is None:
                    m.d.comb += valid.eq(Const(0, 1))
                elif dealloc is None:
                    m.d.sync += valid.eq(alloc)
                elif alloc is None:
                    m.d.sync += valid.eq(valid & ~dealloc)
                else:
                    m.d.sync += valid.eq((valid & ~dealloc) | alloc)

        for base, (in_sig, out_sig) in paired.items():
            width = max(in_sig.width, out_sig.width)
            if self.has_clock:
                reg = Signal(width, name="reg_" + base)
                m.d.sync += reg.eq(in_sig)
                m.d.comb += out_sig.eq(reg)
            else:
                m.d.comb += out_sig.eq(in_sig)

        for out_name, out_sig in self.outputs.items():
            if any(out_name == p[1] for p in paired.values()):
                continue
            m.d.comb += out_sig.eq(Const(0, out_sig.width))

        return m


class UHSCBackendIssueEntriesFamily(Elaboratable):
    """Default deterministic top that instantiates every covered module.

    实例化每个被覆盖模块的默认确定性顶层。
    """

    # Instantiate all covered modules as submodules. / 把所有被覆盖模块实例化为子模块。
    def __init__(self, ports_table: dict) -> None:
        self.ports_table = ports_table
        self.children: dict = {}

    # Elaborate the family wrapper with all covered submodules. / 展开包含全部被覆盖子模块的族包装。
    def elaborate(self, platform) -> Module:
        del platform
        m = Module()
        for name in COVERED_MODULES:
            inst = V2IssueEntryModule(name, self.ports_table[name])
            self.children[name] = inst
            setattr(self, "u_" + name, inst)
            m.submodules[name] = inst
        return m


