class BypassPipeFamily(Elaboratable):
    """One exact bypass/pipe ABI pending locked behavior transcription."""

    def __init__(self, member: str = "BypassNetwork") -> None:
        """Declare the frozen ANSI surface for ``member``."""

        if member not in PORT_SPECS:
            raise ValueError(member)
        self.member = member
        self.specs = PORT_SPECS[member]
        self.ports = {name: Signal(width, name=name) for name, _direction, width in self.specs}

    def _defaults(self, module: Module) -> None:
        """Keep every output deterministic before a member-specific drive."""

        for name, direction, width in self.specs:
            if direction == "output":
                module.d.comb += self.ports[name].eq(Const(0, width))

    def elaborate(self, platform: Any) -> Module:
        del platform
        module = Module()
        self._defaults(module)
        return module


def build_verilog(configuration: Any, injected_dependencies: Any) -> str:
    """Export deterministic Verilog for one same-name datapath member."""

    del injected_dependencies
    member = "BypassNetwork"
    if isinstance(configuration, dict):
        member = str(configuration.get("module", member))
    elif isinstance(configuration, str):
        member = configuration
    top = BypassPipeFamily(member)
    return verilog.convert(top, name=member, ports=[top.ports[name] for name, _direction, _width in top.specs], emit_src=False)


