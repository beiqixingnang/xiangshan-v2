class BypassPipeFamily(Elaboratable):
    """One exact bypass/pipe ABI pending locked behavior transcription."""

    def __init__(self, member: str = "BypassNetwork") -> None:
        """Declare the frozen ANSI surface for ``member``."""

        if member not in PORT_SPECS:
            raise ValueError(member)
        self.member = member
        self.specs = PORT_SPECS[member]
        self.ports = {
            name: Signal(width, name=name, init=None, reset_less=True)
            if direction == "output" else Signal(width, name=name)
            for name, direction, width in self.specs
        }

    def _defaults(self, module: Module) -> None:
        """Keep every output deterministic before a member-specific drive."""

        for name, direction, width in self.specs:
            if direction == "output":
                module.d.comb += self.ports[name].eq(Const(0, width))

    def _bypass_network(self, module: Module) -> None:
        """Drive the first behavioral slice of ``BypassNetwork``.

        The locked datapath has a transparent Decoupled boundary: every
        ``fromDataPath`` ready is the matching ``toExus`` ready and every
        ``fromDataPath`` valid/control field is copied to ``toExus``.  Source
        selection covers the locked zero, register, immediate and same-cycle
        forward rails plus the first registered bypass rail.  Bypass
        registers are reset-less, matching the Chisel ``RegNext`` /
        ``RegEnable`` state in the frozen reference.
        """

        ports = self.ports
        directions = {name: direction for name, direction, _width in self.specs}

        # Immediate-bearing issue entries in the locked build.  These indices
        # are the flattened Exu order used by ``immInfo`` in the reference.
        imm_index = {
            "int_0_0": 0,
            "int_0_1": 1,
            "int_1_0": 2,
            "int_1_1": 3,
            "int_2_0": 4,
            "int_2_1": 5,
            "int_3_0": 6,
            "vf_0_1": 14,
            "mem_0_0": 18,
            "mem_1_0": 19,
        }

        def fit_immediate(value: Any, bits: int, width: int, signed: bool) -> Any:
            """Match ImmExtractor's 64-bit intermediate and wider fit."""

            base_width = min(width, 64)
            source = value[:bits]
            if bits > base_width:
                source = value[:base_width]
            elif bits < base_width:
                if signed:
                    source = Cat(source, *[value[bits - 1] for _ in range(base_width - bits)])
                else:
                    source = Cat(source, Const(0, base_width - bits))
            if width > base_width:
                source = Cat(source, Const(0, width - base_width))
            return source[:width]

        def immediate_value(imm: Any, imm_type: Any, width: int) -> Any:
            """Implement the locked ImmUnion selector for source ``imm``."""

            values = (
                (1, fit_immediate(Cat(Const(0, 1), imm[:12]), 13, width, True)),  # SB
                (2, fit_immediate(Cat(Const(0, 12), imm[:20]), 32, width, True)),  # U
                (3, fit_immediate(Cat(Const(0, 1), imm[:20]), 21, width, True)),  # UJ
                (4, fit_immediate(imm, 12, width, True)),  # I
                (5, fit_immediate(imm, 22, width, True)),  # Z
                (8, fit_immediate(imm, 6, width, False)),  # B6
                (9, fit_immediate(imm, 5, width, True)),  # OPIVIS
                (10, fit_immediate(imm, 5, width, False)),  # OPIVIU
                (11, fit_immediate(imm, 32, width, True)),  # LUI32
                (12, fit_immediate(imm, 11, width, True)),  # VSETVLI
                (13, fit_immediate(imm, 15, width, True)),  # VSETIVLI
                (15, fit_immediate(imm, 6, width, False)),  # VRORVI
            )
            result: Any = Const(0, width)
            for selector, value in values:
                result = Mux(imm_type == Const(selector, len(imm_type)), value, result)
            return result

        # Locked forward source filters. The encoded exuSources value starts
        # at one; value zero is the no-hit case.
        forward_sources = {
            "int": ("int_0_0", "int_1_0", "int_2_0", "int_3_0", "mem_2_0", "mem_3_0", "mem_4_0"),
            "fp": ("fp_0_0", "fp_1_0", "fp_2_0"),
        }

        # ``bypassDataVec`` is a reset-less ``RegEnable(data, valid)`` bank
        # in the locked Scala. Keep one register per source and update it
        # only when that EXU presents a valid result. The frozen build has no
        # active readBypass2 sink, so selector 3 remains pending evidence.
        bypass_domain = ClockDomain("bypass", reset_less=True)
        bypass_domain.clk = ports["clock"]
        module.domains.bypass = bypass_domain
        bypass_registers: dict[str, Signal] = {}
        for source_exu in tuple(dict.fromkeys(forward_sources["int"] + forward_sources["fp"])):
            data_name = f"io_fromExus_{source_exu}_bits_data"
            valid_name = f"io_fromExus_{source_exu}_valid"
            if directions.get(data_name) != "input" or directions.get(valid_name) != "input":
                continue
            data = ports[data_name]
            state = Signal(len(data), name=f"bypassDataVec_{source_exu}_r",
                           init=None, reset_less=True)
            bypass_registers[source_exu] = state
            with cast(Any, module.If(ports[valid_name])):
                module.d.bypass += state.eq(data)

        def forward_value(exu: str, selector: Any, width: int) -> Any | None:
            """Select one same-cycle forward source for a scalar sink."""

            if exu.startswith("fp_"):
                sources = forward_sources["fp"]
            elif exu.startswith("int_") or exu in {
                "mem_0_0", "mem_1_0", "mem_2_0", "mem_3_0", "mem_4_0", "mem_7_0", "mem_8_0",
            }:
                sources = forward_sources["int"]
            else:
                return None
            result: Any = Const(0, width)
            for index, source_exu in enumerate(sources, start=1):
                data_name = f"io_fromExus_{source_exu}_bits_data"
                if directions.get(data_name) != "input":
                    continue
                data = ports[data_name]
                if len(data) > width:
                    data = data[:width]
                elif len(data) < width:
                    data = Cat(data, Const(0, width - len(data)))
                result = Mux(selector == Const(index, len(selector)), data, result)
            return result

        def registered_value(selector: Any, width: int,
                            sources: tuple[str, ...]) -> Any:
            """Select one delayed source value for DataSource.bypass."""

            result: Any = Const(0, width)
            for index, source_exu in enumerate(sources, start=1):
                state = bypass_registers.get(source_exu)
                if state is None:
                    continue
                data: Any = state
                if len(data) > width:
                    data = data[:width]
                elif len(data) < width:
                    data = Cat(data, Const(0, width - len(data)))
                result = Mux(selector == Const(index, len(selector)), data, result)
            return result

        # Ready is a direct Decoupled pass-through.  There are no ready
        # outputs for occupied input entries in the frozen ABI.
        for name, direction, _width in self.specs:
            if direction != "output" or not name.startswith("io_fromDataPath_"):
                continue
            if not name.endswith("_ready"):
                continue
            exu = name[len("io_fromDataPath_"):-len("_ready")]
            ready_name = f"io_toExus_{exu}_ready"
            if directions.get(ready_name) == "input":
                module.d.comb += ports[name].eq(ports[ready_name])

        # Every non-source output field is a same-name bundle connection.
        for name, direction, width in self.specs:
            if direction != "output" or not name.startswith("io_toExus_"):
                continue
            tail = name[len("io_toExus_"):]
            input_name = f"io_fromDataPath_{tail}"
            if "_bits_src_" in tail:
                exu, source_text = tail.split("_bits_src_", 1)
                try:
                    source_index = int(source_text)
                except ValueError:
                    source_index = -1
                source_name = input_name
                selector_name = (
                    f"io_fromDataPath_{exu}_bits_dataSources_{source_index}_value"
                )
                if directions.get(source_name) == "input" and directions.get(selector_name) == "input":
                    source = ports[source_name]
                    selector = ports[selector_name]
                    imm_value = Const(0, width)
                    info_idx = imm_index.get(exu)
                    if info_idx is not None:
                        imm_name = f"io_fromDataPath_immInfo_{info_idx}_imm"
                        imm_type_name = f"io_fromDataPath_immInfo_{info_idx}_immType"
                        if directions.get(imm_name) == "input" and directions.get(imm_type_name) == "input":
                            imm = ports[imm_name]
                            imm_value = immediate_value(imm, ports[imm_type_name], width)
                    # A few memory entries carry a prebuilt immediate on the
                    # Exu input instead of an immInfo slot.
                    elif directions.get(f"io_fromDataPath_{exu}_bits_imm") == "input":
                        raw_imm = ports[f"io_fromDataPath_{exu}_bits_imm"]
                        imm_value = raw_imm[:width]
                    exu_selector_name = (
                        f"io_fromDataPath_{exu}_bits_exuSources_{source_index}_value"
                    )
                    forward = (
                        forward_value(exu, ports[exu_selector_name], width)
                        if directions.get(exu_selector_name) == "input" else None
                    )
                    selected = Mux(
                        selector == Const(0, len(selector)), Const(0, width),
                        Mux(selector == Const(4, len(selector)), imm_value,
                            Mux(selector == Const(8, len(selector)), source, Const(0, width)))
                    )
                    if forward is not None:
                        selected = Mux(selector == Const(1, len(selector)), forward, selected)
                        selected = Mux(
                            selector == Const(2, len(selector)),
                            registered_value(
                                ports[exu_selector_name], width,
                                forward_sources["fp"] if exu.startswith("fp_") else forward_sources["int"],
                            ),
                            selected,
                        )
                    module.d.comb += ports[name].eq(
                        selected
                    )
                    continue
            if directions.get(input_name) == "input":
                module.d.comb += ports[name].eq(ports[input_name])

        # ``reset`` remains unused by the reset-less bypass register bank;
        # the ABI still carries it for the surrounding datapath contract.

    def elaborate(self, platform: Any) -> Module:
        del platform
        module: Any = Module()
        if self.member == "BypassNetwork":
            self._defaults(module)
            self._bypass_network(module)
            return module
        if self.member != "PipeGroupConnect":
            self._defaults(module)
            return module

        core = _PipeGroupConnectCore(self.specs, self.ports["clock"], self.ports["reset"])
        module.submodules.pipe_group_connect = core
        module.d.comb += [
            core.ports[name].eq(self.ports[name])
            for name, direction, _width in self.specs
            if direction == "input" and name not in ("clock", "reset")
        ]
        module.d.comb += [
            self.ports[name].eq(core.ports[name])
            for name, direction, _width in self.specs
            if direction == "output"
        ]
        return module


class _PipeGroupConnectCore(Elaboratable):
    """Six-lane state machine kept as a child so payload state stays explicit."""

    def __init__(self, specs: tuple[PortSpec, ...], clock: Signal, reset: Signal) -> None:
        self.specs = specs
        self.clock = clock
        self.reset = reset
        self.ports = {
            name: Signal(width, name=name, init=None, reset_less=True)
            if direction == "output" else Signal(width, name=name)
            for name, direction, width in specs
            if name not in ("clock", "reset")
        }

    def elaborate(self, platform: Any) -> Module:
        del platform
        module: Any = Module()

        # The reference uses an asynchronously reset ``sync`` clock domain;
        # dataVec registers intentionally remain reset-less and are only
        # written when their lane accepts an input transaction.
        domain = ClockDomain("sync", async_reset=True)
        domain.clk = self.clock
        domain.rst = self.reset
        module.domains.sync = domain

        valid_vec = [Signal(name=f"validVec_{lane}") for lane in range(6)]
        any_valid = Signal(name="any_valid")
        can_acc = Signal(name="canAcc")
        module.d.comb += [
            any_valid.eq(valid_vec[0] | valid_vec[1] | valid_vec[2] |
                         valid_vec[3] | valid_vec[4] | valid_vec[5]),
            can_acc.eq(self.ports["io_outAllFire"] | ~any_valid),
        ]

        for lane in range(6):
            in_prefix = f"io_in_{lane}_"
            out_prefix = f"io_out_{lane}_"
            module.d.comb += self.ports[f"io_in_{lane}_ready"].eq(can_acc)
            # Keep the public output as a combinational wire. A direct alias
            # lets Yosys fold the payload register into the output port and
            # add an initializer that the locked unreset reference lacks.
            module.d.comb += self.ports[f"io_out_{lane}_valid"].eq(
                valid_vec[lane] ^ Const(0)
            )

            # The input/output payload schemas are identical for each lane.
            # Keep one reset-less register per locked field so the exported
            # RTL preserves the reference's uninitialised payload semantics.
            data_fields: list[tuple[str, Signal]] = []
            for name, direction, width in self.specs:
                if direction != "input" or not name.startswith(in_prefix + "bits_"):
                    continue
                field = name[len(in_prefix):]
                output_name = out_prefix + field
                output_port = self.ports.get(output_name)
                if output_port is None:
                    raise ValueError(f"missing PipeGroupConnect output {output_name}")
                # ``init=None`` is required here: the locked reference's
                # payload registers have no reset or declaration initializer.
                # Chisel's Bundle flattening omits the public ``bits_``
                # wrapper in its state names (``dataVec_0_instr``), while
                # the ports retain it. Match that locked state naming so the
                # inductive rail can pair every register directly.
                state_field = field.removeprefix("bits_")
                data = Signal(width, name=f"dataVec_{lane}_{state_field}",
                               init=None, reset_less=True)
                data_fields.append((field, data))
                module.d.comb += output_port.eq(data ^ Const(0, width))

            input_valid = self.ports[f"io_in_{lane}_valid"]
            output_ready = self.ports[f"io_out_{lane}_ready"]
            capture = input_valid & can_acc
            with module.If(self.ports["io_flush"]):
                module.d.sync += valid_vec[lane].eq(0)
            with module.Elif(capture):
                module.d.sync += valid_vec[lane].eq(1)
            with module.Elif(output_ready):
                module.d.sync += valid_vec[lane].eq(0)
            # The locked reference writes payload registers in a separate
            # clocked block, so a capture still updates data during flush;
            # only the valid state gives flush priority.
            with module.If(capture):
                module.d.sync += [
                    data.eq(self.ports[f"io_in_{lane}_{field}"])
                    for field, data in data_fields
                ]
        return module


def build_verilog(configuration: Any, injected_dependencies: Any) -> str:
    """Export deterministic Verilog for one same-name datapath member."""

    del injected_dependencies
    member = "BypassNetwork"
    if isinstance(configuration, dict):
        member = str(configuration.get("module", member))
    elif isinstance(configuration, str):
        member = configuration
    top = BypassPipeFamily(member)
    return verilog.convert(top, name=member, ports=[top.ports[name] for name, _direction, _width in top.specs], emit_src=False)


def main() -> None:
    """Print the default bypass RTL."""

    print(build_verilog({"module": "BypassNetwork"}, {}))


if __name__ == "__main__":
    main()
