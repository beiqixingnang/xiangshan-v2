def match32(pattern: str, value):
    # Match a 32-bit pattern string against a value / 32 位模式串与值匹配
    bits = [c for c in pattern if c in "01?"]
    if len(bits) > 32:
        bits = bits[-32:]
    mask = 0
    expected = 0
    for i, b in enumerate(bits):
        pos = len(bits) - 1 - i
        if b in "01":
            mask |= 1 << pos
            if b == "1":
                expected |= 1 << pos
    return (value & mask) == expected


